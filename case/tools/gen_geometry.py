#!/usr/bin/env python3
"""Generate case/geometry.scad from the WP4 Ergogen results.

Inputs (all in the shared Ergogen frame, mm, y up, origin = centre of the
outer-column bottom key):
  pcb/ergogen/preview/points.yaml   key centres and rotations (copy of output/points/points.yaml)
  pcb/ergogen/config.yaml           anchors: mounting holes, controller, display, reset, power switch, JST
  pcb/ergogen/preview/*.dxf         outlines (read directly by OpenSCAD, not copied)

Usage: python3 case/tools/gen_geometry.py [--src DIR]
  --src DIR   use DIR/points/points.yaml (a fresh `ergogen --debug` output/) instead of preview/points.yaml
Requires PyYAML.
"""
import argparse
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ERG = os.path.join(ROOT, "pcb", "ergogen")


def evaluate(expr, units):
    """Evaluate an Ergogen unit expression such as '0.5 kp' or 'ctrl_y - 22.65 - 8'."""
    if isinstance(expr, (int, float)):
        return float(expr)
    s = re.sub(r"(\d(?:\.\d+)?)\s+([A-Za-z_]\w*)", r"\1*\2", str(expr))
    return float(eval(s, {"__builtins__": {}}, dict(units)))


def dxf_bbox(path):
    """Bounding box of LINE / ARC / CIRCLE entities of an Ergogen DXF."""
    import math
    t = [x.strip() for x in open(path).read().split("\n")]
    i = t.index("ENTITIES")
    ents, j, cur = [], i + 1, None
    while not (t[j] == "0" and t[j + 1] == "ENDSEC"):
        if t[j] == "0":
            cur = {"type": t[j + 1]}
            ents.append(cur)
            j += 2
            continue
        cur.setdefault(t[j], []).append(t[j + 1])
        j += 2
    xs, ys = [], []
    for e in ents:
        g = lambda k: float(e[k][0])
        if e["type"] == "LINE":
            xs += [g("10"), g("11")]
            ys += [g("20"), g("21")]
        elif e["type"] == "ARC":
            a0, a1 = g("50"), g("51")
            if a1 <= a0:
                a1 += 360
            for q in range(int(a0 * 2), int(a1 * 2) + 1):
                th = math.radians(q / 2)
                xs.append(g("10") + g("40") * math.cos(th))
                ys.append(g("20") + g("40") * math.sin(th))
        elif e["type"] == "CIRCLE":
            xs += [g("10") - g("40"), g("10") + g("40")]
            ys += [g("20") - g("40"), g("20") + g("40")]
    return min(xs), max(xs), min(ys), max(ys)


def load(src):
    cfg = yaml.safe_load(open(os.path.join(ERG, "config.yaml")))
    ppath = os.path.join(ERG, "preview", "points.yaml") if src is None else os.path.join(src, "points", "points.yaml")
    pts = yaml.safe_load(open(ppath))
    return cfg, pts, ppath


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=None)
    ap.add_argument("--out", default=os.path.join(ROOT, "case", "geometry.scad"))
    a = ap.parse_args()
    cfg, pts, ppath = load(a.src)
    units = {k: evaluate(v, {}) if not isinstance(v, str) else None for k, v in cfg["units"].items()}
    units = {k: v for k, v in units.items() if v is not None}
    units.update({"kp": 19.05, "ks": 19.05})
    for k, v in cfg["units"].items():  # derived units, in order
        units[k] = evaluate(v, units)

    def anchor(name):
        an = cfg["anchors"][name]
        ref = pts[an["ref"]]
        assert abs(ref["r"]) < 1e-9, "anchor refs with rotation are not supported"
        sx, sy = (evaluate(v, units) for v in an.get("shift", [0, 0]))
        return (ref["x"] + sx, ref["y"] + sy, float(an.get("rotate", 0)))

    names = ["ctrl", "display", "h1", "h2", "h3", "h4", "h5", "pwr", "rst", "bat"]
    anc = {n: anchor(n) for n in names}

    def fmt(v):
        return ("%.4f" % v).rstrip("0").rstrip(".")

    keys = sorted(pts.items(), key=lambda kv: (kv[1]["x"], kv[1]["y"]))
    out = []
    out.append("// GENERATED by case/tools/gen_geometry.py. Do not edit by hand.")
    out.append("// Source: %s and pcb/ergogen/config.yaml (Ergogen frame, mm, y up)." % os.path.relpath(ppath, ROOT))
    out.append("// Rotation r is Ergogen's (counter-clockwise positive), same as OpenSCAD rotate().")
    out.append("")
    out.append("// [name, x, y, r]; 42-key = all, 36-key = without the matrix_outer_* column")
    out.append("keys_42 = [")
    for n, p in keys:
        out.append('  ["%s", %s, %s, %s],' % (n, fmt(p["x"]), fmt(p["y"]), fmt(p["r"])))
    out.append("];")
    out.append("keys_36 = [")
    for n, p_ in keys:
        if not n.startswith("matrix_outer_"):
            out.append('  ["%s", %s, %s, %s],' % (n, fmt(p_["x"]), fmt(p_["y"]), fmt(p_["r"])))
    out.append("];")
    out.append("")
    out.append("// M2 mounting holes H1..H5 (centres)")
    out.append("holes = [%s];" % ", ".join("[%s, %s]" % (fmt(anc[h][0]), fmt(anc[h][1])) for h in ["h1", "h2", "h3", "h4", "h5"]))
    out.append("")
    for n, var in [("ctrl", "ctrl_pos"), ("display", "display_pos"), ("rst", "reset_pos"), ("pwr", "pwr_pos"), ("bat", "jst_pos")]:
        out.append("%s = [%s, %s, %s];  // x, y, rotation" % (var, fmt(anc[n][0]), fmt(anc[n][1]), fmt(anc[n][2])))
    out.append("")
    bb = dxf_bbox(os.path.join(ERG, "preview", "board_42.dxf"))
    # B.Cu socket pads of the reversible switch footprint (pcb/footprints/ergogen/switch_mx_choc_reversible.js,
    # lines "B.Cu"), converted from KiCad (y down) to the Ergogen key frame (y up): [x, y, w, h].
    out.append("// B.Cu hot-swap pads in the key frame [x, y, w, h]: MX pad 1, MX pad 2, Choc pad 1, Choc pad 2")
    out.append("// (from switch_mx_choc_reversible.js; used for boss keep-outs, the Choc and MX sockets are both avoided)")
    out.append("socket_pads_b = [[7.085, -2.54, 2.55, 2.5], [-5.842, -5.08, 2.55, 2.5], [8.275, 3.75, 2.6, 2.6], [-3.275, 5.95, 2.6, 2.6]];")
    out.append("")
    out.append("// PCB outline bounding box [xmin, xmax, ymin, ymax] of board_42.dxf (right edge = strip edge, for edge slots)")
    out.append("board_bbox = [%s];" % ", ".join(fmt(v) for v in bb))
    out.append("")
    out.append("// Outline files, read in place from the WP4 preview/ copy (all share the Ergogen frame; see README)")
    out.append('dxf_dir = "../pcb/ergogen/preview/";')
    out.append("")
    open(a.out, "w").write("\n".join(out))
    print("wrote", os.path.relpath(a.out, ROOT))
    for n in names:
        print("  %-8s %s" % (n, tuple(round(v, 4) for v in anc[n])))


if __name__ == "__main__":
    sys.exit(main())
